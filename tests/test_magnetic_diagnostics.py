"""Gate-only diagnostic isolation, timing and export fault tests."""
import hashlib,json,pathlib,re,shutil,subprocess,tempfile,unittest,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
from verify_modular import body_hashes
class MagneticDiagnostics(unittest.TestCase):
    def test_native_trace_and_actual_exporter(self):
        compiler=shutil.which('g++')
        if not compiler:self.skipTest('g++ required')
        with tempfile.TemporaryDirectory() as tmp:
            for source in ['magnetic_trace_test.cpp','magnetic_service_test.cpp']:
                exe=str(pathlib.Path(tmp)/source)
                subprocess.run([compiler,'-std=c++17','-Wall','-Wextra','-Werror',
                    '-I'+str(ROOT/'tests/magnetic_stubs'),'-I'+str(ROOT/'include'),
                    str(ROOT/'tests'/source),'-o',exe],check=True)
                subprocess.run([exe],check=True)
    def test_production_detector_only_renamed_and_observed(self):
        text=(ROOT/'src/services/VehicleDetector.cpp').read_text()
        normalized=text.replace('beamAPin','magSensorPin').replace('beamBPin','beamSensorPin')
        normalized=normalized.replace('    sampleMagneticDiagnostics(rawA, rawB);','')
        normalized=normalized.replace('                markMagneticBeamVehicle();','')
        hashes=dict(body_hashes(normalized))
        # .10 reviewed detector and persistence bodies, not regenerated by .11.
        expected=json.loads((ROOT/'tests/magnetic_detector_baseline.json').read_text())
        for name,value in expected.items():self.assertEqual(hashes[name],value,name)
        service=(ROOT/'src/services/MagneticDiagnostics.cpp').read_text()
        self.assertNotRegex(service,r'\b(countTheCar|persistCountState|recordOfficialVehicle|recordPendingVehicle)\s*\(')
        self.assertNotRegex(service,r'\b(totalDailyCars|totalShowCars|inParkCars|hourlyCount)\b')
    def test_pin_and_hook_contract(self):
        config=(ROOT/'include/traffic/DeviceConfig.h').read_text()
        for name,pin in [('beamAPin',32),('beamBPin',33),('magneticSensorPin',25)]:
            self.assertRegex(config,rf'#define {name} {pin}\b')
        for path in list((ROOT/'src').rglob('*.cpp'))+list((ROOT/'include/traffic').glob('*.h')):
            self.assertNotRegex(path.read_text(),r'\b(magSensorPin|beamSensorPin)\b',str(path))
        main=(ROOT/'src/main.cpp').read_text()
        self.assertIn('initializeMagneticDiagnostics();',main)
        self.assertLess(main.index('    detectCar();'),main.index('    serviceMagneticDiagnostics();'))
if __name__=='__main__':unittest.main()
